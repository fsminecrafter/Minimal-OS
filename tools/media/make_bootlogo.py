#!/usr/bin/env python3
"""Icon.png -> src/resources/bootlogo.h: the boot animation's logo as an 8-bit coverage mask
(0 = background, 255 = the logo's white), so the kernel can draw it at any size and brightness.

    python3 tools/media/make_bootlogo.py [Icon.png] [src/resources/bootlogo.h] [size]
"""
import sys
from pathlib import Path
from PIL import Image

src = Path(sys.argv[1] if len(sys.argv) > 1 else "Icon.png")
out = Path(sys.argv[2] if len(sys.argv) > 2 else "src/resources/bootlogo.h")
size = int(sys.argv[3]) if len(sys.argv) > 3 else 320

im = Image.open(src).convert("RGB")
bg = im.getpixel((2, 2))                       # the icon's dark background
im = im.resize((size, size), Image.LANCZOS)
lum_bg = 0.299 * bg[0] + 0.587 * bg[1] + 0.114 * bg[2]
data = []
for y in range(size):
    for x in range(size):
        r, g, b = im.getpixel((x, y))
        l = 0.299 * r + 0.587 * g + 0.114 * b
        c = (l - lum_bg) / (255.0 - lum_bg)
        data.append(max(0, min(255, int(round(c * 255)))))

# The rows that hold anything: the kernel skips the empty bands.
rows = [y for y in range(size) if any(data[y * size:(y + 1) * size])]
lines = [
    "// Generated by tools/media/make_bootlogo.py from %s: do not edit." % src.name,
    "// The boot animation's logo, %dx%d, one byte of coverage per pixel (0 background, 255 logo)." % (size, size),
    "#pragma once",
    "#include <stdint.h>",
    "#define BOOTLOGO_SIZE %du" % size,
    "#define BOOTLOGO_FIRST_ROW %du" % rows[0],
    "#define BOOTLOGO_LAST_ROW %du" % rows[-1],
    "static const uint8_t k_bootlogo[%d] = {" % (size * size),
]
for i in range(0, len(data), 24):
    lines.append("    " + ",".join(str(v) for v in data[i:i + 24]) + ",")
lines.append("};")
out.write_text("\n".join(lines) + "\n")
print("wrote %s: %dx%d, rows %d..%d" % (out, size, size, rows[0], rows[-1]))
