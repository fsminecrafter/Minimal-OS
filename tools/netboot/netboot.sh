#!/usr/bin/env bash
# Network boot (PXE) for Minimal-OS on the local LAN.
#
#   tools/netboot/netboot.sh prepare        build the TFTP folder from the ISO (no root)
#   sudo tools/netboot/netboot.sh serve     prepare, then serve until Ctrl+C
#
# The router keeps handing out IP addresses. dnsmasq runs in proxy-DHCP mode:
# it only tells PXE clients where to get GRUB. GRUB then fetches kernel.bin and
# the .mpkg modules over TFTP and boots them with the ISO's own grub.cfg, so
# the boot menu is the same as when booting the ISO from a USB stick.
#
# Settings (environment variables):
#   NETBOOT_IFACE   LAN interface to serve on   (default: interface of the default route)
#   NETBOOT_ISO     ISO to boot                 (default: dist/x86_64/kernel.iso)
#   NETBOOT_LOG_PORT  UDP port for the network log (default: 5140; 0 turns it off)
#
# Network log: the booted PC sends its whole kernel log (boot messages,
# program output, Mxplorer's console with site errors) back here. It is
# printed while 'serve' runs and saved in build/netboot/logs/ (latest.log
# is the newest).
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
ISO="${NETBOOT_ISO:-$REPO/dist/x86_64/kernel.iso}"
OUT="$REPO/build/netboot"
TFTP="$OUT/tftp"
LOG_PORT="${NETBOOT_LOG_PORT:-5140}"
GRUB_PC_DIR=/usr/lib/grub/i386-pc
GRUB_EFI_DIR=/usr/lib/grub/x86_64-efi

IFACE="${NETBOOT_IFACE:-$(ip -4 route show default | awk '{print $5; exit}')}"
SERVER_IP="$(ip -4 -o addr show dev "$IFACE" | awk '{split($4,a,"/"); print a[1]; exit}')"
SUBNET="$(ip -4 route show dev "$IFACE" scope link | awk '{split($1,a,"/"); print a[1]; exit}')"

die() { echo "netboot: $*" >&2; exit 1; }

# Modules built into the GRUB images. Everything else is loaded over TFTP.
GRUB_MODULES="tftp normal configfile echo test true multiboot2 all_video gfxterm font"

prepare() {
	[ -f "$ISO" ] || die "ISO not found: $ISO (run make first)"
	[ -n "$SERVER_IP" ] || die "no IPv4 address on $IFACE"

	echo "netboot: unpacking $ISO"
	rm -rf "$TFTP"
	mkdir -p "$TFTP"
	# Only /boot is needed: kernel.bin, the .mpkg modules, grub.cfg and fonts.
	xorriso -osirrox on -indev "$ISO" -extract /boot "$TFTP/boot" >/dev/null 2>&1 \
		|| die "could not unpack $ISO"
	chmod -R u+w,a+rX "$TFTP"
	# GRUB's 'test -f' cannot see files over TFTP (no directory listing), so
	# grub.cfg's "load the firmware if it is there" checks are always false
	# on netboot. Decide them here instead, against the unpacked files.
	if [ -f "$TFTP/boot/mosfirmware.mpkg" ]; then
		sed -i 's|\[ -f /boot/mosfirmware.mpkg \]|true|' "$TFTP/boot/grub/grub.cfg"
	else
		sed -i 's|\[ -f /boot/mosfirmware.mpkg \]|false|' "$TFTP/boot/grub/grub.cfg"
	fi
	# Tell the kernel where to send its log (netlog.c).
	if [ "$LOG_PORT" != 0 ]; then
		sed -i "s|^\(\s*multiboot2 /boot/kernel.bin\)\(.*\)$|\1\2 netlog=$SERVER_IP:$LOG_PORT|" \
			"$TFTP/boot/grub/grub.cfg"
	fi
	# The ISO's BIOS GRUB modules are replaced by the host's matching set below.
	rm -rf "$TFTP/boot/grub/i386-pc" "$TFTP/boot/grub/x86_64-efi"

	# The server address is built into GRUB, so the boot does not depend on
	# GRUB reading the proxy-DHCP reply (some UEFI GRUB builds ignore it).
	local prefix="(tftp,$SERVER_IP)/boot/grub"

	# Startup script built into GRUB: load the menu straight away. Without
	# it, GRUB first probes for per-machine files (grub.cfg-01-<mac>,
	# grub.cfg-<ip>, ...) and can hang for minutes retrying them.
	cat > "$OUT/early.cfg" <<-EOF
	echo "Minimal-OS netboot: loading menu from $SERVER_IP ..."
	set root=(tftp,$SERVER_IP)
	set prefix=$prefix
	configfile $prefix/grub.cfg
	echo "Minimal-OS netboot: could not load $prefix/grub.cfg"
	EOF

	echo "netboot: building GRUB for BIOS PXE"
	mkdir -p "$TFTP/boot/grub/i386-pc"
	cp "$GRUB_PC_DIR"/*.mod "$GRUB_PC_DIR"/*.lst "$TFTP/boot/grub/i386-pc/"
	grub-mkimage -d "$GRUB_PC_DIR" -O i386-pc-pxe -p "$prefix" -c "$OUT/early.cfg" \
		-o "$TFTP/boot/grub/i386-pc/core.0" pxe $GRUB_MODULES

	if [ -d "$GRUB_EFI_DIR" ]; then
		echo "netboot: building GRUB for UEFI PXE"
		mkdir -p "$TFTP/boot/grub/x86_64-efi"
		cp "$GRUB_EFI_DIR"/*.mod "$GRUB_EFI_DIR"/*.lst "$TFTP/boot/grub/x86_64-efi/"
		grub-mkimage -d "$GRUB_EFI_DIR" -O x86_64-efi -p "$prefix" -c "$OUT/early.cfg" \
			-o "$TFTP/boot/grub/x86_64-efi/core.efi" efinet $GRUB_MODULES
	else
		echo "netboot: $GRUB_EFI_DIR missing, UEFI netboot disabled (install grub-efi-amd64-bin)" >&2
	fi

	chmod -R a+rX "$TFTP"
	echo "$SERVER_IP" > "$OUT/server-ip"
	echo "netboot: ready in $TFTP (server $SERVER_IP on $IFACE)"
}

write_dnsmasq_conf() {
	cat > "$OUT/dnsmasq.conf" <<EOF
# Generated by tools/netboot/netboot.sh
port=0
interface=$IFACE
bind-interfaces
except-interface=lo
dhcp-range=$SUBNET,proxy
log-dhcp

enable-tftp
tftp-root=$TFTP

pxe-prompt="Minimal-OS network boot",1
# BIOS: dnsmasq adds ".0" to the BIOS file name itself.
pxe-service=x86PC,"Minimal-OS (BIOS)",boot/grub/i386-pc/core
pxe-service=X86-64_EFI,"Minimal-OS (UEFI)",boot/grub/x86_64-efi/core.efi
pxe-service=BC_EFI,"Minimal-OS (UEFI)",boot/grub/x86_64-efi/core.efi
EOF
}

UFW_RULES=("67/udp" "69/udp" "4011/udp")
[ "$LOG_PORT" != 0 ] && UFW_RULES+=("$LOG_PORT/udp")

firewall_open() {
	command -v ufw >/dev/null && ufw status | grep -q "Status: active" || return 0
	echo "netboot: opening firewall on $IFACE (udp ${UFW_RULES[*]%/udp})"
	for r in "${UFW_RULES[@]}"; do
		ufw allow in on "$IFACE" to any port "${r%/*}" proto udp comment minimal-os-netboot >/dev/null
	done
}

firewall_close() {
	command -v ufw >/dev/null && ufw status | grep -q "Status: active" || return 0
	echo "netboot: closing firewall rules"
	for r in "${UFW_RULES[@]}"; do
		ufw delete allow in on "$IFACE" to any port "${r%/*}" proto udp >/dev/null 2>&1 || true
	done
}

serve() {
	[ "$(id -u)" -eq 0 ] || die "serve needs root: sudo $0 serve"

	# Build as the normal user so build/ does not end up owned by root.
	if [ -n "${SUDO_USER:-}" ]; then
		sudo -u "$SUDO_USER" NETBOOT_IFACE="$IFACE" NETBOOT_ISO="$ISO" "$0" prepare
	else
		prepare
	fi
	write_dnsmasq_conf

	firewall_open
	LOG_PID=
	if [ "$LOG_PORT" != 0 ]; then
		# Runs as the normal user so the log files are not owned by root.
		if [ -n "${SUDO_USER:-}" ]; then
			sudo -u "$SUDO_USER" python3 "$REPO/tools/netboot/netlog_listen.py" \
				--port "$LOG_PORT" --dir "$OUT/logs" &
		else
			python3 "$REPO/tools/netboot/netlog_listen.py" --port "$LOG_PORT" --dir "$OUT/logs" &
		fi
		LOG_PID=$!
	fi
	trap '[ -n "$LOG_PID" ] && kill "$LOG_PID" 2>/dev/null; firewall_close' EXIT
	echo
	echo "netboot: serving Minimal-OS on $IFACE ($SERVER_IP). Ctrl+C to stop."
	echo "netboot: on the other PC, pick the network/PXE boot entry in the boot menu."
	echo
	dnsmasq --no-daemon --conf-file="$OUT/dnsmasq.conf" --user=nobody
}

case "${1:-}" in
	prepare) prepare ;;
	serve) serve ;;
	*) echo "usage: $0 prepare | sudo $0 serve" >&2; exit 2 ;;
esac
