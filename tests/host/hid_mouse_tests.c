// Host tests for the HID mouse report parser. Build: make test-host
#include <stdio.h>
#include "mouse/hid_mouse.h"

static int failures;
#define CHECK(c, m) do { if (!(c)) { printf("FAIL: %s\n", m); failures++; } } while (0)

int main(void) {
    hid_mouse_layout_t l;
    uint8_t b; int32_t x, y, w;

    // Plain 3-button wheel mouse, no report IDs: [buttons, x, y, wheel].
    static const uint8_t plain[] = {
        0x05,0x01,0x09,0x02,0xA1,0x01,0x09,0x01,0xA1,0x00,0x05,0x09,0x19,0x01,0x29,0x03,
        0x15,0x00,0x25,0x01,0x95,0x03,0x75,0x01,0x81,0x02,0x95,0x01,0x75,0x05,0x81,0x01,
        0x05,0x01,0x09,0x30,0x09,0x31,0x09,0x38,0x15,0x81,0x25,0x7F,0x75,0x08,0x95,0x03,
        0x81,0x06,0xC0,0xC0 };
    CHECK(hid_mouse_parse(plain, sizeof plain, &l), "plain parses");
    CHECK(l.report_id == 0 && l.wheel.size == 8 && l.button_count == 3, "plain layout");
    const uint8_t r1[] = { 0x05, 0xFE, 0x03, 0xFF };
    CHECK(hid_mouse_decode(&l, r1, 4, &b, &x, &y, &w) && b == 5 && x == -2 && y == 3 && w == -1,
          "plain report");

    // Gaming mouse: report ID 1, 16 buttons, 16-bit X/Y, wheel, AC pan.
    static const uint8_t gaming[] = {
        0x05,0x01,0x09,0x02,0xA1,0x01,0x85,0x01,0x09,0x01,0xA1,0x00,0x05,0x09,0x19,0x01,
        0x29,0x10,0x15,0x00,0x25,0x01,0x95,0x10,0x75,0x01,0x81,0x02,0x05,0x01,0x16,0x01,
        0x80,0x26,0xFF,0x7F,0x75,0x10,0x95,0x02,0x09,0x30,0x09,0x31,0x81,0x06,0x15,0x81,
        0x25,0x7F,0x75,0x08,0x95,0x01,0x09,0x38,0x81,0x06,0x05,0x0C,0x0A,0x38,0x02,0x95,
        0x01,0x81,0x06,0xC0,0xC0 };
    CHECK(hid_mouse_parse(gaming, sizeof gaming, &l), "gaming parses");
    CHECK(l.report_id == 1 && l.x.bit == 16 && l.x.size == 16 && l.wheel.bit == 48, "gaming layout");
    const uint8_t r2[] = { 0x01, 0x02, 0x00, 0x2C, 0x01, 0xF6, 0xFF, 0x01, 0x00 };
    CHECK(hid_mouse_decode(&l, r2, 9, &b, &x, &y, &w) && b == 2 && x == 300 && y == -10 && w == 1,
          "gaming report");
    const uint8_t other[] = { 0x02, 0x10, 0x00 };
    CHECK(!hid_mouse_decode(&l, other, 3, &b, &x, &y, &w), "other report ID ignored");

    // Logitech style: ID 2, 16 buttons, 12-bit X/Y packed, wheel, pan.
    static const uint8_t logi[] = {
        0x05,0x01,0x09,0x02,0xA1,0x01,0x85,0x02,0x09,0x01,0xA1,0x00,0x05,0x09,0x19,0x01,
        0x29,0x10,0x15,0x00,0x25,0x01,0x95,0x10,0x75,0x01,0x81,0x02,0x05,0x01,0x16,0x01,
        0xF8,0x26,0xFF,0x07,0x75,0x0C,0x95,0x02,0x09,0x30,0x09,0x31,0x81,0x06,0x15,0x81,
        0x25,0x7F,0x75,0x08,0x95,0x01,0x09,0x38,0x81,0x06,0xC0,0xC0 };
    CHECK(hid_mouse_parse(logi, sizeof logi, &l), "logitech parses");
    // x = -5 (0xFFB), y = 7 (0x007): bytes FB, 7F, 00 after buttons.
    const uint8_t r3[] = { 0x02, 0x01, 0x00, 0xFB, 0x7F, 0x00, 0xFE };
    CHECK(hid_mouse_decode(&l, r3, 7, &b, &x, &y, &w) && b == 1 && x == -5 && y == 7 && w == -2,
          "logitech report");

    if (failures) return 1;
    printf("hid mouse tests passed\n");
    return 0;
}
